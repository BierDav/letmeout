#!/usr/bin/env python3
"""Writes the API docs of letmeout's functions from Typst's own documentation.

  api-docs.py            fetch the latest docs from typst.app and update the sources
  api-docs.py --check    fail if the sources differ from what the latest docs give

letmeout's `grid`, `line`, and `align` take the same arguments as
Typst's `grid`, `line`, and `align`. Their doc comments copy Typst's
summary and parameter docs, with types and defaults, and add what each part
does in HTML. The HTML notes are written by hand in scripts/api.toml.

A generated block starts with a "Generated by scripts/api-docs.py" line and
ends at the next blank line. Code lines inside it are kept, unless api.toml
asks for a generated signature. Every parameter Typst documents needs a note
or an exclusion in api.toml, and every note needs a parameter, so a parameter that Typst adds
or removes stops the update until someone decides what it does in HTML.
"""
from html.parser import HTMLParser
import os, re, sys, textwrap, tomllib, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = "https://typst.app/docs/reference/"
MARKER = "// Generated by scripts/api-docs.py"
WIDTH = 88
VOID = {"br", "img", "hr", "input", "meta", "link", "source", "wbr", "use"}


class Node:
    def __init__(self, tag, attrs, parent):
        self.tag, self.attrs, self.parent, self.children = tag, dict(attrs), parent, []

    def classes(self):
        return (self.attrs.get("class") or "").split()

    def elements(self):
        return [c for c in self.children if isinstance(c, Node)]

    def find_all(self, test):
        for child in self.elements():
            if test(child):
                yield child
            yield from child.find_all(test)

    def text(self):
        return "".join(c if isinstance(c, str) else c.text() for c in self.children)


class Tree(HTMLParser):
    """The page as a tree. typst.app writes well-formed HTML."""

    def __init__(self, html):
        super().__init__(convert_charrefs=True)
        self.root = self.node = Node("root", {}, None)
        self.feed(html)

    def handle_starttag(self, tag, attrs):
        node = Node(tag, attrs, self.node)
        self.node.children.append(node)
        if tag not in VOID:
            self.node = node

    def handle_endtag(self, tag):
        node = self.node
        while node.parent and node.tag != tag:
            node = node.parent
        if node.parent:
            self.node = node.parent

    def handle_data(self, data):
        self.node.children.append(data)


def inline(node):
    """Markdown for inline HTML."""
    if isinstance(node, str):
        return node
    inner = "".join(inline(c) for c in node.children)
    if node.tag == "code":
        return "`" + re.sub(r"\s+", " ", node.text()).strip() + "`"
    if node.tag in ("strong", "b"):
        return f"**{inner}**"
    if node.tag in ("em", "i"):
        return f"_{inner}_"
    if node.tag == "br":
        return " "
    if node.tag in ("svg", "button") or "tooltip-context" in node.classes():
        return ""
    return inner


def blocks(nodes, indent=""):
    """Markdown paragraphs and lists for block HTML. Examples are left out."""
    out = []
    for node in nodes:
        if isinstance(node, str):
            if node.strip():
                out.append(indent + re.sub(r"\s+", " ", node).strip())
            continue
        if node.tag in ("details", "pre", "nav") or {"previewed-code", "page-end-buttons"} & set(node.classes()):
            continue
        if node.tag in ("ul", "ol"):
            items = []
            for n, item in enumerate(node.find_all(lambda e: e.tag == "li" and e.parent is node), 1):
                bullet = "- " if node.tag == "ul" else f"{n}. "
                parts = blocks(merge_inline(item.children), " " * len(bullet)) or [""]
                items.append(indent + bullet + parts[0].lstrip() + "".join("\n" + p for p in parts[1:]))
            out.append("\n".join(items))
        elif node.tag in ("p", "h4") or node.tag == "li":
            text = re.sub(r"\s+", " ", inline(node)).strip()
            if node.tag == "h4":
                text = f"**{text}**"
            if text:
                out.append(indent + text)
        elif node.tag == "div":
            out += blocks(merge_inline(node.children), indent)
        else:
            text = re.sub(r"\s+", " ", inline(node)).strip()
            if text:
                out.append(indent + text)
    return out


def merge_inline(nodes):
    """Loose text and inline elements between blocks form one paragraph."""
    grouped, run = [], []
    for node in nodes:
        if isinstance(node, Node) and node.tag in ("p", "ul", "ol", "div", "details", "pre", "h4"):
            if run:
                grouped.append(Node("p", {}, None))
                grouped[-1].children = run
                run = []
            grouped.append(node)
        else:
            run.append(node)
    if run and "".join(inline(n) for n in run).strip():
        grouped.append(Node("p", {}, None))
        grouped[-1].children = run
    return grouped


def section(heading):
    """The elements after a heading, up to the next heading of the same or a higher level."""
    siblings = heading.parent.children
    stop = {"h1", "h2", "h3"} if heading.tag == "h3" else {"h1", "h2"}
    out = []
    for node in siblings[siblings.index(heading) + 1:]:
        if isinstance(node, Node) and node.tag in stop:
            break
        out.append(node)
    return merge_inline(out)


def fetch(path):
    request = urllib.request.Request(DOCS + path + "/", headers={"User-Agent": "letmeout-api-docs"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read().decode("utf-8")


def parse(html, name):
    root = Tree(html).root
    versions = re.findall(r'href="/docs/changelog/(\d+\.\d+\.\d+)/"', html)
    if not versions:
        sys.exit(f"{name}: no Typst version found on the docs page")
    summary = next(root.find_all(lambda e: e.tag == "h1" and e.attrs.get("id") == "summary"), None)
    if summary is None:
        sys.exit(f"{name}: no summary on the docs page")
    params = []
    for h3 in root.find_all(lambda e: e.tag == "h3" and (e.attrs.get("id") or "").startswith("parameters-")):
        info = next(h3.find_all(lambda e: "additional-info" in e.classes()), None)
        types = [a.text().strip() for a in info.find_all(lambda e: "pill" in e.classes())] if info else []
        mods = [s.text().strip() for small in h3.find_all(lambda e: "mod" in e.classes())
                for s in small.find_all(lambda e: e.tag == "span" and "aria-describedby" in e.attrs)]
        default = next(h3.find_all(lambda e: "default" in e.classes()), None)
        default = next(default.find_all(lambda e: e.tag == "code"), None) if default else None
        params.append({
            "name": h3.attrs["id"].removeprefix("parameters-"),
            "types": types,
            "positional": "Positional" in mods,
            "required": "Required" in mods,
            "variadic": "Variadic" in mods,
            "default": re.sub(r"\s+", " ", default.text()).strip() if default else None,
            "docs": blocks(section(h3)),
        })
    if not params:
        sys.exit(f"{name}: no parameters on the docs page")
    return {"version": versions[0], "summary": blocks(section(summary)), "params": params}


def wrap(text, prefix, rest=None):
    """Wraps markdown, keeping list markers and their indentation."""
    rest = prefix if rest is None else rest
    lines = []
    for n, raw in enumerate(text.split("\n")):
        body = raw.lstrip(" ")
        indent = " " * (len(raw) - len(body))
        marker = re.match(r"(- |\d+\. )", body)
        hang = " " * len(marker.group(1)) if marker else ""
        lines += textwrap.wrap(body, WIDTH, initial_indent=(prefix if n == 0 else rest) + indent,
                               subsequent_indent=rest + indent + hang,
                               break_long_words=False, break_on_hyphens=False) or [rest.rstrip()]
    return lines


# Typst markup that would change a note's meaning, outside of raw text.
MARKUP = re.compile(r"//|[*_#$<>@\[\]\\~]")
# Markup that starts a list, heading, or term at the start of a line.
LINE_START = re.compile(r"(-|\+|=|/|\d+\.)(\s|$)")


def escape_markup(text):
    parts = re.split(r"(`[^`]*`)", text)
    return "".join(part if part.startswith("`")
                   else MARKUP.sub(lambda m: "".join("\\" + c for c in m.group(0)), part)
                   for part in parts)


def note(text, prefix, rest=None):
    """The HTML note as a Typst block quote, which editors such as Tinymist highlight."""
    rest = prefix if rest is None else rest
    lines = wrap("#quote(block: true)[*Note:* " + escape_markup(text.strip()) + "]", prefix, rest)
    ticks = lines[0].count("`")
    for i in range(1, len(lines)):
        body = lines[i][len(rest):]
        if ticks % 2 == 0 and LINE_START.match(body):
            lines[i] = rest + "\\" + body
        ticks += body.count("`")
    return lines


def doc_lines(spec, docs):
    paragraphs = list(spec.get("summary", [])) if "summary" in spec else docs["summary"]
    if isinstance(paragraphs, str):
        paragraphs = [paragraphs]
    out = []
    for p in paragraphs:
        out += ["///"] if out else []
        out += wrap(p.strip(), "/// ")
    if spec.get("html"):
        out += ["///"] + note(spec["html"], "/// ")
    out.append("///")
    for param in documented(spec, docs):
        kind = ", ".join(param["types"]) + (", ..." if param["variadic"] else "")
        if spec.get("signature"):
            default = "the surrounding page setting" + (f"; Typst's default is `{param['default']}`" if param["default"] else "")
        else:
            default = f"`{param['default']}`" if param["default"] else None
        role = ", ".join(r for r, on in (("required", param["required"]), ("positional", param["positional"])) if on)
        text = [param["docs"][0] if param["docs"] else ""] + param["docs"][1:]
        head = f"- {param['name']} ({kind}): "
        if len(head) > WIDTH * 2 // 3:
            # many types: the description starts on the next line
            lines = wrap(head.rstrip(), "/// ", "///   ") + wrap(text[0], "///   ")
        else:
            lines = wrap(text[0], "/// " + head, "///   ")
        for p in text[1:]:
            lines += ["///"] + wrap(p, "///   ")
        extra = ([f"Default: {default}."] if default else []) + ([f"This parameter is {role}."] if role else [])
        if extra:
            lines += ["///"] + wrap(" ".join(extra), "///   ")
        lines += ["///"] + note(spec["params"][param["name"]], "///   ")
        out += lines + ["///"]
    out.append("/// -> " + spec.get("returns", "content"))
    return out


def documented(spec, docs):
    """The parameters the function takes: Typst's, without those api.toml excludes."""
    return [p for p in docs["params"] if p["name"] not in spec.get("exclude", {})]


def signature_lines(name, spec, docs):
    """Named parameters default to `inherit`, so only given arguments reach Typst.
    Parameters listed in `positional` pass through an argument sink."""
    positional = spec.get("positional", [])
    params = [p["name"] for p in documented(spec, docs) if p["name"] not in positional]
    sink = f"..{positional[0]}" if positional else None
    return ([f"#let {name}("] + [f"  {p}: inherit," for p in params] + ([f"  {sink},"] if sink else [])
            + [f") = {spec['signature']}(("] + [f"  {p}: {p}," for p in params]
            + ([f"), {sink})"] if sink else ["))"]))


def check_notes(name, spec, docs):
    taken = {p["name"] for p in documented(spec, docs)}
    noted = set(spec.get("params", {}))
    problems = []
    gone = set(spec.get("exclude", {})) - {p["name"] for p in docs["params"]}
    if gone:
        problems.append(f"excludes parameters Typst no longer documents: {', '.join(sorted(gone))}")
    if taken - noted:
        problems.append(f"no HTML note for {', '.join(sorted(taken - noted))}")
    if noted - taken:
        problems.append(f"notes for parameters Typst no longer documents: {', '.join(sorted(noted - taken))}")
    if problems:
        sys.exit(f"scripts/api.toml [{name}]: " + "; ".join(problems))


def generate(text, name, spec, docs):
    url = DOCS + spec["typst"] + "/"
    block = [f"{MARKER} from the Typst {docs['version']} docs of `{spec['typst'].split('/')[-1]}`,",
             f"// {url}. Edit scripts/api.toml, not this block."] + doc_lines(spec, docs)
    lines = text.split("\n")
    starts = [i for i, l in enumerate(lines) if l.startswith(MARKER)
              and any(re.match(rf"#let {re.escape(name)}\(", x) for x in region(lines, i))]
    if len(starts) > 1:
        sys.exit(f"{spec['file']}: more than one generated block for {name}")
    if starts:
        start = starts[0]
        old = region(lines, start)
        end = start + len(old)
    else:
        found = [i for i, l in enumerate(lines) if re.match(rf"#let {re.escape(name)}\(", l)]
        if len(found) != 1:
            sys.exit(f"{spec['file']}: expected one definition of {name}, found {len(found)}")
        start = found[0]
        while start > 0 and lines[start - 1].startswith("//"):
            start -= 1
        old = region(lines, start)
        end = start + len(old)
    if spec.get("signature"):
        code = signature_lines(name, spec, docs)
    else:
        code = [l for l in old if not l.startswith("//")]
    return "\n".join(lines[:start] + block + code + lines[end:])


def region(lines, start):
    """A block runs from its start to the next blank line."""
    out = []
    for line in lines[start:]:
        if not line.strip():
            break
        out.append(line)
    return out


def main(args):
    if args not in ([], ["--check"]):
        print(__doc__, file=sys.stderr)
        return 2
    with open(os.path.join(ROOT, "scripts/api.toml"), "rb") as f:
        specs = tomllib.load(f)
    pages, files, version = {}, {}, None
    for name, spec in specs.items():
        if spec["typst"] not in pages:
            pages[spec["typst"]] = parse(fetch(spec["typst"]), spec["typst"])
        docs = pages[spec["typst"]]
        version = docs["version"]
        check_notes(name, spec, docs)
        path = os.path.join(ROOT, spec["file"])
        if path not in files:
            files[path] = open(path, encoding="utf-8").read()
        files[path] = generate(files[path], name, spec, docs)
    stale = []
    for path, text in files.items():
        if open(path, encoding="utf-8").read() != text:
            stale.append(os.path.relpath(path, ROOT))
            if not args:
                open(path, "w", encoding="utf-8").write(text)
    verb = "out of date" if args else "updated"
    for path in stale:
        print(f"{verb}: {path}", file=sys.stderr)
    print(f"API docs from Typst {version}: {len(stale)} file(s) {verb}", file=sys.stderr)
    return 1 if args and stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
